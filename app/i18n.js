  var fallback = 'en';

  // Map a BCP 47 tag such as "cs-CZ", "pt_BR" or "zh-Hans-CN" to a supported language.
  function language(candidates) {
    for (var i = 0; i < candidates.length; i++) {
      var tag = candidates[i];
      if (typeof tag !== 'string' || tag.length > 35) continue;
      var primary = tag.trim().toLowerCase().split(/[-_]/)[0];
      if (/^[a-z]{2,3}$/.test(primary) && Object.prototype.hasOwnProperty.call(strings, primary)) return primary;
    }
    return fallback;
  }
  // Locale sources in priority order: webOS system locale, legacy Palm property, then the browser.
  function detect(scope) {
    var candidates = [];
    try { if (scope.webOSSystem && typeof scope.webOSSystem.locale === 'string') candidates.push(scope.webOSSystem.locale); } catch (e) { /* Not on webOS. */ }
    try { if (scope.PalmSystem && typeof scope.PalmSystem.locale === 'string') candidates.push(scope.PalmSystem.locale); } catch (e) { /* Not on legacy webOS. */ }
    try {
      var nav = scope.navigator;
      if (nav) {
        if (typeof nav.language === 'string') candidates.push(nav.language);
        if (Array.isArray(nav.languages)) candidates = candidates.concat(nav.languages.slice(0, 5));
      }
    } catch (e) { /* No navigator. */ }
    return language(candidates);
  }
  function translator(lang) {
    var table = strings[lang] || strings[fallback], base = strings[fallback];
    function t(key, params) {
      var text = Object.prototype.hasOwnProperty.call(table, key) ? table[key] :
        Object.prototype.hasOwnProperty.call(base, key) ? base[key] : key;
      return params ? text.replace(/\{([a-z]+)\}/g, function (match, name) {
        return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match;
      }) : text;
    }
    t.language = lang;
    return t;
  }
  return { strings: strings, fallback: fallback, language: language, detect: detect, translator: translator,
    languages: Object.keys(strings) };
